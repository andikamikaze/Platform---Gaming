/** @typedef {keyof typeof paths} IconName */

const hasOwn = (object, key) => Object.prototype.hasOwnProperty.call(object, key);

/** Fallback yang aman jika nama tidak dikenal. */
export function iconPaths(name) {
  return hasOwn(paths, name) ? paths[name] : paths.info;
}

function escapeAttr(value) {
  return String(value).replace(/[&<>"']/g, (char) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[char]);
}

/**
 * Render satu ikon sebagai string SVG.
 * @param {string} name nama ikon dari `paths`
 * @param {{ size?: number|string, className?: string, title?: string, strokeWidth?: number|string }} [options]
 * @returns {string}
 */
export function iconSVG(name, options = {}) {
  const { size, className = "", title = "", strokeWidth = 2 } = options;
  const dimension = size == null ? "" : ` width="${escapeAttr(size)}" height="${escapeAttr(size)}"`;
  const classes = className ? ` class="${escapeAttr(className)}"` : "";
  const accessibility = title
    ? ` role="img" aria-label="${escapeAttr(title)}"`
    : ' aria-hidden="true" focusable="false"';
  const segments = iconPaths(name).map((d) => `<path d="${escapeAttr(d)}"/>`).join("");
  return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${escapeAttr(strokeWidth)}" stroke-linecap="round" stroke-linejoin="round"${dimension}${classes}${accessibility}>${segments}</svg>`;
}

/**
 * Isi semua placeholder `<span data-icon="nama"></span>` di dalam root.
 * Aman dipanggil berulang (idempoten).
 */
export function hydrateIcons(root = globalThis.document) {
  if (!root) return;
  root.querySelectorAll("[data-icon]").forEach((node) => {
    node.classList.add("icon");
    node.innerHTML = iconSVG(node.dataset.icon, { className: node.dataset.iconClass || "" });
  });
}

/** Ganti ikon pada sebuah elemen (untuk ikon dinamis: tema, favorit, dll). */
export function setIcon(node, name) {
  if (!node) return;
  node.classList.add("icon");
  node.setAttribute("data-icon", name);
  node.innerHTML = iconSVG(name);
}
