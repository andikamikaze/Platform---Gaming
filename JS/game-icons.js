/** Nama ikon untuk sebuah game; fallback: kategori → gamepad2. */
export function gameIconFor(id, category) {
  return GAME_ICON[id] || CATEGORY_ICON[category] || "gamepad2";
}

/** Daftar entri mapping yang nama ikonnya tidak dikenal library (kosong = valid). */
export function invalidIconNames() {
  return Object.entries({ ...GAME_ICON, ...CATEGORY_ICON })
    .filter(([, name]) => !Object.prototype.hasOwnProperty.call(paths, name))
    .map(([key, name]) => `${key} → ${name}`);
}
